uint16_t CRC16_MODBUS(uint8_t *data, uint16_t length)
{
    uint16_t crc = 0xFFFF;

    for (uint16_t i = 0; i < length; i++)
    {
        crc ^= data[i];

        for (uint8_t bit = 0; bit < 8; bit++)
        {
            if (crc & 1)
                crc = (crc >> 1) ^ 0xA001;
            else
                crc >>= 1;
        }
    }

    return crc;
}



void SendTelemetry(void)
{
    static uint8_t telemetry_count = 0;

    uint16_t pulse_us = (uint16_t)measured_pulse_us;
    uint8_t frame[8];

    frame[0] = 0xA5;
    frame[1] = 0x04;
    frame[2] = 0x82;
    frame[3] = telemetry_count++;
    frame[4] = pulse_us & 0xFF;
    frame[5] = (pulse_us >> 8) & 0xFF;

    uint16_t crc = CRC16_MODBUS(&frame[1], 5);

    frame[6] = crc & 0xFF;
    frame[7] = (crc >> 8) & 0xFF;

    HAL_UART_Transmit(&huart1, frame, sizeof(frame), 100);
}



void SendAck(uint8_t seq, uint8_t status)
{
    uint8_t frame[7];

    frame[0] = 0xA5;     // Start byte
    frame[1] = 0x03;     // Payload length
    frame[2] = 0x81;     // ACK message type
    frame[3] = seq;      // Echo command sequence
    frame[4] = status;   // 0x00 = OK, 0x01 = invalid pulse

    // CRC covers length + 3 payload bytes
    uint16_t crc = CRC16_MODBUS(&frame[1], 4);

    frame[5] = crc & 0xFF;        // CRC low byte
    frame[6] = (crc >> 8) & 0xFF; // CRC high byte

    HAL_UART_Transmit(&huart1, frame, 7, 100);
}

void ReceiveAndProcessFrame(void)
{
    uint8_t start;
    uint8_t length;
    uint8_t payload[16];
    uint8_t crc_bytes[2];

    // 1. Wait for the start byte
    if (HAL_UART_Receive(&huart1, &start, 1, 100) != HAL_OK)
        return;

    if (start != 0xA5)
        return;

    // 2. Read payload length
    if (HAL_UART_Receive(&huart1, &length, 1, 100) != HAL_OK)
        return;

    // Prevent reading beyond our buffer
    if (length == 0 || length > sizeof(payload))
        return;

    // 3. Read the payload
    if (HAL_UART_Receive(&huart1, payload, length, 100) != HAL_OK)
        return;

    // 4. Read CRC, low byte first
    if (HAL_UART_Receive(&huart1, crc_bytes, 2, 100) != HAL_OK)
        return;

    uint16_t received_crc =
        (uint16_t)crc_bytes[0] |
        ((uint16_t)crc_bytes[1] << 8);

    // CRC covers LENGTH + PAYLOAD
    uint8_t crc_data[17];
    crc_data[0] = length;

    for (uint8_t i = 0; i < length; i++)
        crc_data[i + 1] = payload[i];

    uint16_t calculated_crc =
        CRC16_MODBUS(crc_data, length + 1);

    // 5. Validate CRC
    if (received_crc != calculated_crc)
    {
        printf("Invalid CRC\r\n");
        return;
    }

    // 6. Process SET_PULSE (type 0x01)
    if (length == 4 && payload[0] == 0x01)
    {
        uint8_t seq = payload[1];

        uint16_t pulse_us =
            (uint16_t)payload[2] |
            ((uint16_t)payload[3] << 8);

        // Accept only the permitted pulse-width range
        if (pulse_us >= 1000 && pulse_us <= 2000)
        {
            __HAL_TIM_SET_COMPARE(
                &htim3, TIM_CHANNEL_1, pulse_us);

            SendAck(seq, 0x00);
        }
        else
        {
            SendAck(seq, 0x01);
        }
    }
}

