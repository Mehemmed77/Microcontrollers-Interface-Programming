void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM2 ||
        htim->Channel != HAL_TIM_ACTIVE_CHANNEL_1)
        return;

    if (capture_state == 0)
    {
        // Rising edge
        capture_rising =
            HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);

        capture_state = 1;

        TIM2->CCER |= TIM_CCER_CC1P;  // Capture falling edge
    }
    else
    {
        // Falling edge
        capture_falling =
            HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);

        measured_pulse_us = capture_falling - capture_rising;
        printf("Measured pulse: %lu us\r\n",
               (unsigned long)measured_pulse_us);

        capture_state = 0;

        TIM2->CCER &= ~TIM_CCER_CC1P; // Capture rising edge
    }
}

